import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import path from 'path';
import { fileURLToPath } from 'url';
import connectDB from './config/db.js';
import authRoutes from './routes/auth.js';
import carRoutes from './routes/cars.js';
import bookingRoutes from './routes/bookings.js';
import settingsRoutes from './routes/settings.js';
import contactRoutes from './routes/contacts.js';
import { requireAuth } from './middleware/auth.js';
const app=express();
const __dirname=path.dirname(fileURLToPath(import.meta.url));
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
const origins=(process.env.CLIENT_URL||'http://localhost:5173').split(',').map(s=>s.trim());
app.use(cors({origin:(origin,cb)=>!origin||origins.includes(origin)?cb(null,true):cb(new Error('Origin not allowed by CORS')),credentials:true}));
app.use(express.json({limit:'1mb'}));
app.use('/uploads',express.static(path.resolve(__dirname,'../uploads')));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'Al Buraak API'}));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,max:10,standardHeaders:true,legacyHeaders:false}),authRoutes);
app.use('/api/cars',carRoutes);
app.use('/api/bookings',bookingRoutes);
app.use('/api/settings',settingsRoutes);
app.use('/api/contacts',contactRoutes);
app.get('/api/admin/me',requireAuth,(req,res)=>res.json({admin:req.admin}));
app.use((err,req,res,next)=>{console.error(err);const status=err.name==='ValidationError'?400:err.name==='CastError'?400:err.message?.includes('Only JPG')?400:500;res.status(status).json({message:status===500?'Server error. Please try again later.':err.message});});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`Al Buraak API running on ${port}`))).catch(err=>{console.error('Database connection failed:',err.message);process.exit(1);});
